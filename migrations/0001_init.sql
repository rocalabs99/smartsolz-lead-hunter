CREATE TABLE IF NOT EXISTS leads (
 id INTEGER PRIMARY KEY AUTOINCREMENT,
 first_name TEXT DEFAULT '', last_name TEXT DEFAULT '', company TEXT NOT NULL,
 title TEXT DEFAULT '', email TEXT DEFAULT '', phone TEXT DEFAULT '', website TEXT DEFAULT '',
 country TEXT DEFAULT '', industry TEXT DEFAULT '', source_url TEXT DEFAULT '',
 consent_status TEXT NOT NULL DEFAULT 'unverified',
 consent_basis TEXT DEFAULT '', consent_date TEXT DEFAULT '', notes TEXT DEFAULT '',
 unsubscribed INTEGER NOT NULL DEFAULT 0, created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE UNIQUE INDEX IF NOT EXISTS idx_leads_email ON leads(email) WHERE email <> '';
CREATE TABLE IF NOT EXISTS campaigns (
 id INTEGER PRIMARY KEY AUTOINCREMENT, name TEXT NOT NULL, subject TEXT NOT NULL,
 body TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'draft',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS sends (
 id INTEGER PRIMARY KEY AUTOINCREMENT, campaign_id INTEGER NOT NULL,
 lead_id INTEGER NOT NULL, status TEXT NOT NULL, detail TEXT DEFAULT '',
 sent_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS suppressions (
 email TEXT PRIMARY KEY, reason TEXT DEFAULT 'Unsubscribed',
 created_at TEXT NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS settings (
 key TEXT PRIMARY KEY, value TEXT NOT NULL
);
